#include "CourseSelect/CourseSelectConst.hpp"

/** @brief Get the player offset for a miniature. @return Offset of 250 units. */
float CourseSelectConst::getPlayerOffsetMiniature() {
    return 250.0f;
}

/** @brief Get the player offset for Bowser. @return Offset of 400 units. */
float CourseSelectConst::getPlayerOffsetKoopa() {
    return 400.0f;
}

/** @brief Get the sideways player offset. @return Offset of 110 units. */
float CourseSelectConst::getPlayerOffsetSide() {
    return 110.0f;
}
